// Generates optimized web assets from assets-src/ into public/.
// Run with `npm run assets` after changing a source image. Outputs are committed,
// so the Docker build does not need sharp's native binary.
import sharp from "sharp";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = (f) => path.join(root, "assets-src", f);
const out = (f) => path.join(root, "public", f);

await mkdir(out("images"), { recursive: true });

// Portrait: upscaled 4x with Real-ESRGAN (x4plus, run locally), cut out with macOS Vision
// (scripts/cutout.swift) and cleaned by scripts/refine-matte.mjs.
const portrait = sharp(src("portrait-cutout.png"));
const { width, height } = await portrait.metadata();
const heroH = Math.round(height * 0.62); // OG card crop: turban to mid-thigh

// Full figure, turban to shoes. Filenames carry a content hash so a new portrait is never
// hidden behind a cached old one (nginx caches images for 30 days).
for (const f of await readdir(out("images"))) if (f.startsWith("portrait")) await rm(out(`images/${f}`));
const variants = {};
for (const [key, w] of [["sm", 420], ["hd", width]]) {
  const buf = await sharp(src("portrait-cutout.png"))
    .resize({ width: w })
    .webp({ quality: 88, alphaQuality: 95, effort: 6 })
    .toBuffer();
  const hash = createHash("sha256").update(buf).digest("hex").slice(0, 10);
  const name = `images/portrait-${key}.${hash}.webp`;
  await sharp(buf).toFile(out(name));
  const meta = await sharp(buf).metadata();
  variants[key] = { src: `/${name}`, width: meta.width, height: meta.height };
}
await writeFile(
  path.join(root, "src/data/assets.ts"),
  `// Generated by scripts/build-assets.mjs — do not edit.\nexport const portrait = ${JSON.stringify(variants, null, 2)} as const;\n`,
);

// Open Graph card 1200x630.
const og = Buffer.from(`
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <defs>
    <linearGradient id="a" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#3a52ff"/><stop offset="1" stop-color="#b9c4ff"/>
    </linearGradient>
  </defs>
  <rect width="1200" height="630" fill="#eef0f5"/>
  <text x="64" y="300" font-family="Helvetica Neue, Arial" font-size="190" font-weight="700" fill="#dfe3ec" letter-spacing="-8">ENGINEER</text>
  <path d="M760 630 V250 a170 170 0 0 1 340 0 V630 Z" fill="url(#a)"/>
  <text x="64" y="420" font-family="Helvetica Neue, Arial" font-size="30" fill="#5b6475">Hey, I'm Jagmeet Singh.</text>
  <text x="64" y="480" font-family="Helvetica Neue, Arial" font-size="52" font-weight="600" fill="#0e1116" letter-spacing="-1.5">AI Engineer</text>
  <text x="64" y="540" font-family="Helvetica Neue, Arial" font-size="34" fill="#0e1116" letter-spacing="-0.5">LLM agents &amp; full-stack platforms</text>
</svg>`);
const ogPortrait = await sharp(src("portrait-cutout.png"))
  .extract({ left: 0, top: 0, width, height: heroH })
  .resize({ height: 560 })
  .png()
  .toBuffer();
const pm = await sharp(ogPortrait).metadata();
await sharp(og)
  .composite([{ input: ogPortrait, left: Math.round(930 - pm.width / 2), top: 630 - pm.height }])
  .png({ compressionLevel: 9 })
  .toFile(out("og.png"));

console.log("assets built", { width, height, heroH });
